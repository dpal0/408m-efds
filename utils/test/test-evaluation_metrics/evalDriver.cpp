#include <fstream>
#include <string>
#include <iostream>
using namespace std;

/* This code does post-processing for the facial detection algorithm.

It generates ground truth data to compare the tests to. To do this, we 
assumes that images were fed into the classifier in the order of all faces 
then all nonfaces. The number of face and nonface images are inputted by 
the user on the command line.

We then counts the number of TP, FP, TN, FN for each cascade, comparing the
cascade's output to the ground truth data. To do this, we reads the 
textfile generated by each cascadev(named out + cascade # + .txt). We then
compare each entry in the textfile to the associated ground truth data.  

We calculate TPR and FPR for each cascade as well as the overall system.

We store all the evaluation metrics in a file. The user names the file
using a command line prompt. */
int main(int argc, char **argv) {

    // number of cascades/iterations to compute
    int NUM_CASCADES = stoi(argv[1]);

    // inputs used to generate ground truth data
    int NUM_FACE = stoi(argv[2]);
    int NUM_NON_FACE = stoi(argv[3]);

    // output file to save results to
    ofstream out(argv[4]);

    // generate ground truth data
    bool* truth = new bool[NUM_FACE + NUM_NON_FACE];
    fill(truth, truth + NUM_FACE, true);
    fill(truth + NUM_FACE + 1, truth + NUM_FACE + NUM_NON_FACE, false);

    // vars used within the loop
    int TP = 0, FP = 0, TN = 0, FN = 0;
    double TPR, FPR, overall_TPR = 1, overall_FPR = 1;
    ifstream real;
    int ind;
    char classification;

    for (int iter = 1; iter <= NUM_CASCADES; iter++) {

        // open current cascade's real data
        real.open("out" + to_string(iter) + ".txt");

        // count TP, FP, TN, FN for current cascade
        while (real >> ind) {

            real >> classification;

            if (classification == 'F') {
                if (truth[ind-1]) {
                    TP++;
                } else {
                    FP++;
                }
            } else {
                if (truth[ind-1]) {
                    FN++;
                } else {
                    TN++;
                }
                real >> classification;
            }
        }

        // calculate TPR & FPR
        TPR = (double)TP / (TP + FN);
        FPR = (double)FP / (FP + TN);
        overall_TPR *= TPR;
        overall_FPR *= FPR;

        // write the current cascade's evaluation metrics to the output file
        out << "(cascade " << iter << ") TP: " << TP << ", FP: " 
            << FP << ", TN: " << TN << ", FN: " << FN 
            << ", TPR: " << TPR << ", FPR: " << FPR <<'\n'; 

        // reset variables for next iteration
        real.close();
        TP = 0;
        FP = 0;
        TN = 0;
        FN = 0;
    }

    // write overall evaluation metrics to the output file
    out << "\nOverall TPR = " << overall_TPR 
        << ", Overall FPR = " << overall_FPR << endl; 

    // clean up memory/workspace
    delete[] truth;
    out.close();
}


